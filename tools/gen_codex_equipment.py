#!/usr/bin/env python3
"""
Builds mods/HexRevival/assets/codex_equipment.txt: equipment pieces Hex Codex lists for a source (a set's chest or
Wheel of Fate, a campaign pack, the arena, the Siege Pack, an event...) that Zymmer's notes (data/zymmer_sources.tsv,
the mod's main source for these pools) do not list there. The mod adds them to the same pools (Zymmer.Source).

Source: Hex Codex, collectibles/equipment (hex-codex.romosjr.workers.dev/collectibles/equipment/): every piece with
the place it was obtained. Usage: tools/gen_codex_equipment.py <equipment.html>
"""
import collections, html, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
page = open(sys.argv[1], encoding="utf-8").read()
m = re.search(r'<astro-island[^>]*EquipmentBrowser[^>]*props="([^"]*)"', page)
if not m: raise SystemExit("no equipment list in " + sys.argv[1])


def plain(v):
    if isinstance(v, list) and len(v) == 2 and isinstance(v[0], int): return plain(v[1])
    if isinstance(v, dict): return {k: plain(x) for k, x in v.items()}
    if isinstance(v, list): return [plain(x) for x in v]
    return v


props = plain(json.loads(html.unescape(m.group(1))))
sources = props["lists"]["sources"]
# The Codex's source names as Zymmer's notes spell them.
RENAME = {"Howlings Plains Pack": "Howling Plains Pack", "Frost Ring Arena": "Frost Ring Arena Rewards",
          "Kickstarter": "Kickstarter Rewards", "Kickstarter - Blood Dragon Deck": "Kickstarter Rewards",
          "Kismet's Reserve Pack - Vampires": "Kismet's Reserve Pack", "Convocation 2015": "Events - Hex Convocation 2015",
          "Gencon 2016": "Events - Gencon 2016", "Holiday": "Events - Holiday"}
EVENT = re.compile(r"^(Ardor Day|Feast of Abundance|Haunted Harvest|Night of Bells|Questmas|Sea Festival) [0-9]{4}$")


def zname(src):
    if src in RENAME: return RENAME[src]
    if EVENT.match(src): return "Events - " + src
    return src


zym = collections.defaultdict(set)
with open(os.path.join(ROOT, "data", "zymmer_sources.tsv"), encoding="utf-8") as f:
    next(f)
    for line in f:
        p = line.rstrip("\n").split("\t")
        if len(p) >= 3 and p[1] == "e": zym[p[0]].add(p[2].strip().lower())

extra = collections.defaultdict(list)
for row in props["packed"].split("\n"):
    r = row.split("|")
    if len(r) < 8 or not r[7].isdigit(): continue
    src, name = zname(sources[int(r[7])]), r[2].strip()
    if name.lower() not in zym[src]: extra[src].append(name)

out = os.path.join(ROOT, "mods", "HexRevival", "assets", "codex_equipment.txt")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("# HEX Revival: equipment Hex Codex lists for a source that Zymmer's notes do not (generated by tools/gen_codex_equipment.py).\n")
    f.write("# Format: '<source, as in Zymmer's notes>\\t<equipment name>'.\n")
    for src in sorted(extra):
        for name in sorted(set(extra[src])): f.write("%s\t%s\n" % (src, name))
print(sum(len(set(v)) for v in extra.values()), "pieces in", len(extra), "sources ->", os.path.normpath(out))
for src in sorted(extra): print("  %-35s %d" % (src, len(set(extra[src]))))
