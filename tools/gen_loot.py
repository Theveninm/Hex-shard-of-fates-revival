#!/usr/bin/env python3
"""Generates LootData.cs from data/az1_pack_loot_tables.csv (community "AZ1 Loot Tables", 2016).

The spreadsheet is kept as is (reference). Its misspelt names are corrected through
data/loot_name_fixes.csv (sheet_name,game_name,reason; names compared case-insensitively), so that
LootData.cs only holds exact game names.

Usage: python3 tools/gen_loot.py
"""
import csv, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.reader(open(os.path.join(root, 'data/az1_pack_loot_tables.csv'), encoding='utf-8')))
fixes = {}
with open(os.path.join(root, 'data/loot_name_fixes.csv'), encoding='utf-8') as f:
    for r in csv.DictReader(f):
        fixes[r['sheet_name'].strip().lower()] = r['game_name'].strip()
out = []
out.append('// Generated by tools/gen_loot.py from data/az1_pack_loot_tables.csv. Do not edit by hand.')
out.append('namespace HexRevival')
out.append('{')
out.append('    internal static class LootData')
out.append('    {')
out.append('        /// <summary>Pack name, packs opened, then per entry: category (c=card, e=equipment, u=unique equipment), name, rarity, % drop chance.</summary>')
out.append('        public static readonly string[][] Packs =')
out.append('        {')
for p in range(6):
    base = p * 9
    name = rows[0][base].replace(' Pack', '')
    opened = rows[0][base + 1].split(':')[1].strip()
    items = [name, opened]
    for ci, cat in enumerate('ceu'):
        seen = {}
        for r in rows[2:]:
            n, rar, pct = (x.strip() for x in r[base + ci * 3:base + ci * 3 + 3])
            if not n: continue
            n = fixes.get(n.lower(), n)
            k = n.lower()
            if k in seen: continue
            seen[k] = 1
            items += [cat, n, rar, pct.rstrip('%')]
    out.append('            new[] { ' + ', '.join('"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"' for s in items) + ' },')
out.append('        };')
out.append('    }')
out.append('}')
open(os.path.join(root, 'mods/HexRevival/src/HexRevival/LootData.cs'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('ok')
