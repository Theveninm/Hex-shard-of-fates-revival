#!/usr/bin/env python3
"""
Builds mods/HexRevival/assets/sleeve_sources.txt: how each of the game's 425 deck sleeves was obtained, from Hex Codex's
sleeve list (hex-codex.romosjr.workers.dev/collectibles/sleeves/, its "how each was obtained" text). The game's own
sleeve items only carry their names; the mod matches them by name (Sleeves.cs).

Usage: download the page (its HTML holds the list), then
  tools/gen_sleeves.py <sleeves.html>
"""
import html, json, os, re, sys

page = open(sys.argv[1], encoding="utf-8").read()
m = re.search(r'<astro-island[^>]*SleeveBrowser[^>]*props="([^"]*)"', page)
if not m: raise SystemExit("no sleeve list in " + sys.argv[1])


def plain(v):
    """Astro's serialized props: [type, value] pairs."""
    if isinstance(v, list) and len(v) == 2 and isinstance(v[0], int): return plain(v[1])
    if isinstance(v, dict): return {k: plain(x) for k, x in v.items()}
    if isinstance(v, list): return [plain(x) for x in v]
    return v


sleeves = plain(json.loads(html.unescape(m.group(1)))["sleeves"])
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mods", "HexRevival", "assets", "sleeve_sources.txt")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("# HEX Revival: how each deck sleeve was obtained (generated by tools/gen_sleeves.py).\n")
    f.write("# Source: Hex Codex, collectibles/sleeves (%d sleeves). Format: '<sleeve name>\\t<how it was obtained>'.\n" % len(sleeves))
    for s in sorted(sleeves, key=lambda s: s["name"]):
        f.write("%s\t%s\n" % (s["name"].strip(), (s.get("reason") or "").strip().replace("\t", " ").replace("\n", " ")))
print(len(sleeves), "sleeves ->", os.path.normpath(out))
